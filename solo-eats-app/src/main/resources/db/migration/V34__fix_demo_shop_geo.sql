-- ============================================================
-- 修复：演示门店种子坐标与用户端默认定位相距约 10km，超出 5km 配送半径
-- Flyway V34 / MySQL 8.0 / utf8mb4
--
-- 【为什么改】
--   1. 现象：用户端首页 GET /api/v1/c/shops?lng=116.397428&lat=39.90923
--      返回 total=0，前端展示「附近暂无营业门店」；但 t_shop.id=1 的
--      status=1（营业）、deleted=0，数据本身是存在的。
--   2. 根因：V21 把演示门店放在望京（lng=116.470000, lat=39.990000），
--      而用户端 Index.vue 在未授权定位时按天安门（116.397428, 39.90923）
--      兜底，两点直线距离约 10.4km。
--      ShopGeoServiceImpl#nearby 的默认查询半径为 DEFAULT_RADIUS_M=5000，
--      用户端 loadShops 调用 fetchNearbyShops 时未传 radius，因此走 5km；
--      门店在 10km 外被半径过滤掉，结果为空。
--   3. 判定：5km 是外卖业务的合理配送半径，前端兜底坐标也是合理兜底值，
--      两者都不该动。错的是 seed 数据把演示门店放到了 10km 外，
--      与前端默认定位不匹配。故本迁移只修数据，不改
--      DEFAULT_RADIUS_M、不改前端默认定位、不改前端传参逻辑。
--   4. 目标值：演示门店迁至天安门东侧（lng=116.400000, lat=39.912000），
--      与默认定位点直线距离约 379m，同时落在 5km 查询半径内。
--   5. address/district 同步改为与坐标自洽的地址，避免「东长安街的坐标
--      配望京的地址」这类前后端展示矛盾；city 保持「北京市」不变。
--   6. 配送围栏 t_shop_delivery_area(id=2101) 的圆心必须一起迁移：
--      ShopGeoServiceImpl#inRange 优先读「已启用围栏」(status=0)，
--      只在无围栏时才回落 t_shop.delivery_radius_m。若只改 t_shop 坐标
--      而围栏圆心仍留在望京，首页能查到门店，但用户下单
--      delivery-check 会返回 inRange=false（「超出配送范围，距门店 379 米」），
--      同一个 bug 只是从首页转移到了下单页。围栏半径 3000m 不变。
--   7. 幂等：两条语句都是「主键定点 + deleted=0」的等值 UPDATE，
--      不触碰其他门店/围栏；重复执行结果完全一致。
--      历史迁移 V21 已执行记录不改动，本修复只能以新增版本的方式落地。
-- ============================================================

SET NAMES utf8mb4;
SET time_zone = '+08:00';

-- ------------------------------------------------------------
-- 1. 演示门店：坐标与地址迁至天安门东侧（距前端默认定位约 379m）
-- ------------------------------------------------------------
UPDATE t_shop
SET lng      = 116.400000,
    lat      = 39.912000,
    address  = '北京市东城区东长安街',
    district = '东城区'
WHERE id = 1
  AND deleted = 0;

-- ------------------------------------------------------------
-- 2. 演示门店配送围栏：圆形围栏圆心跟随门店迁移（半径保持 3000m）
-- ------------------------------------------------------------
UPDATE t_shop_delivery_area
SET center_lng = 116.400000,
    center_lat = 39.912000
WHERE id = 2101
  AND shop_id = 1
  AND deleted = 0;
